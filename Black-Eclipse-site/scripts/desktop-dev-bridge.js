#!/usr/bin/env node
// Make the installed desktop shell serve THIS repository checkout.
//
// Why: the packaged desktop app ships a frozen copy of the UI under
// `<install>\app`. On launch it prefers that copy, so the desktop window can
// drift from the build this checkout produces even though both are the same
// Next.js app. On a developer machine we want exactly one UI: the repo's `.next`.
//
// This script replaces the packaged `app` with a tiny bridge:
//   <install>\app\scripts\desktop-server.js  ->  <repo>\scripts\desktop-server.js
// The original bundled payload is renamed to `app.bundled-<version>` and left
// untouched. The shell's own root discovery then finds `app` (its packaged
// layout), runs the bridge, and the bridge starts `next start` from the repo
// against the same `.next` build the web app uses.
//
// Run `npm run desktop:dev-bridge` after a fresh desktop install, or whenever
// the desktop app must be re-pointed at this checkout. To go back to the
// self-contained build, rename `app.bundled-<version>` back to `app`.
//
// Windows only (the packaged desktop shell is Windows-first today).

const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const INSTALL = path.join(
  process.env.LOCALAPPDATA || path.join(os.homedir(), "AppData", "Local"),
  "Programs",
  "BlackEclipse",
);
const PACKAGED_APP = path.join(INSTALL, "app");
const BRIDGE_DIR = path.join(PACKAGED_APP, "scripts");
const BRIDGE = path.join(BRIDGE_DIR, "desktop-server.js");

// The shell runs these BY PATH from its packaged root (`<root>\scripts\<name>`).
// Replacing only `desktop-server.js` left "Apply update" and "Restart Eclipse"
// spawning files that did not exist inside the bridge, so the in-app update
// silently did nothing. Every script the shell invokes needs a shim.
const BRIDGED_SCRIPTS = ["desktop-server.js", "update-apply.js", "desktop-refresh.js"];

function bridgeSource(script) {
  return `// Dev bridge generated by Black-Eclipse-site/scripts/desktop-dev-bridge.js.
// Delegates this installed desktop shell to the repository checkout so the
// desktop window and the web app always serve the same build and scripts.
const path = require("path");
const repo = ${JSON.stringify(ROOT)};
process.chdir(repo);
require(path.join(repo, "scripts", ${JSON.stringify(script)}));
`;
}

function log(message) {
  console.log(`[desktop:dev-bridge] ${message}`);
}

function readVersion(dir) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    return typeof pkg.version === "string" ? pkg.version : "unknown";
  } catch {
    return "unknown";
  }
}

function isBridge(dir) {
  try {
    return fs.readFileSync(path.join(dir, "scripts", "desktop-server.js"), "utf8")
      .includes("desktop-dev-bridge.js");
  } catch {
    return false;
  }
}

/**
 * Stop process trees still running from the install directory.
 *
 * Renaming `app` fails with EBUSY while the bundled server (`app\server.js`),
 * its vendored Python harness, or the window itself is alive. A window that
 * crashed or was closed can leave exactly that orphaned server tree behind, so
 * the bridge must clear it — these processes all belong to the install we are
 * about to replace, and the relaunch starts fresh ones.
 */
function stopInstalledProcesses() {
  if (process.platform !== "win32") return [];
  const prefix = INSTALL.replace(/'/g, "''");
  const script =
    "Get-CimInstance Win32_Process | Where-Object { " +
    `($_.ExecutablePath -like '${prefix}\\*') -or ($_.CommandLine -like '*${prefix}\\*') ` +
    "} | Select-Object -ExpandProperty ProcessId";
  const out = spawnSync("powershell", ["-NoProfile", "-Command", script], {
    encoding: "utf8",
    windowsHide: true,
  });
  const pids = (out.stdout || "")
    .split(/\s+/)
    .map((s) => Number(s.trim()))
    .filter((n) => Number.isFinite(n) && n > 0 && n !== process.pid);
  for (const pid of pids) {
    spawnSync("taskkill", ["/F", "/T", "/PID", String(pid)], { stdio: "ignore" });
  }
  return pids;
}

function main() {
  if (!fs.existsSync(INSTALL)) {
    throw new Error(`desktop install not found: ${INSTALL}`);
  }
  const exe = path.join(INSTALL, "Black Eclipse.exe");
  if (!fs.existsSync(exe)) {
    throw new Error(`desktop shell not found: ${exe}`);
  }

  if (fs.existsSync(PACKAGED_APP) && !isBridge(PACKAGED_APP)) {
    const stopped = stopInstalledProcesses();
    if (stopped.length) {
      log(`stopped ${stopped.length} process(es) still running from the install (pid ${stopped.join(", ")})`);
    }
    const bundled = path.join(INSTALL, `app.bundled-${readVersion(PACKAGED_APP)}`);
    if (fs.existsSync(bundled)) {
      throw new Error(
        `both ${PACKAGED_APP} and ${bundled} exist — move ${path.basename(bundled)} aside first`,
      );
    }
    fs.renameSync(PACKAGED_APP, bundled);
    log(`bundled payload preserved at ${bundled}`);
  }

  fs.mkdirSync(BRIDGE_DIR, { recursive: true });
  for (const script of BRIDGED_SCRIPTS) {
    fs.writeFileSync(path.join(BRIDGE_DIR, script), bridgeSource(script), "utf8");
  }
  const prefs = path.join(PACKAGED_APP, ".black-eclipse", "desktop-prefs.json");
  if (!fs.existsSync(prefs)) {
    // Keep the previous window prefs if the bundled payload has them.
    const bundledPrefs = fs
      .readdirSync(INSTALL)
      .filter((name) => name.startsWith("app.bundled-"))
      .map((name) => path.join(INSTALL, name, ".black-eclipse", "desktop-prefs.json"))
      .find((candidate) => fs.existsSync(candidate));
    if (bundledPrefs) {
      fs.mkdirSync(path.dirname(prefs), { recursive: true });
      fs.copyFileSync(bundledPrefs, prefs);
    }
  }

  log(`desktop now serves ${ROOT}`);
  log("close Black Eclipse, then reopen it — the window will load the repo build");
}

try {
  main();
} catch (err) {
  console.error(`[desktop:dev-bridge] ${err.message}`);
  process.exit(1);
}
