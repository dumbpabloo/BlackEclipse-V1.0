"""`eclipse_report` — assemble a computed report and save it to the Artifact Center."""

from __future__ import annotations

from typing import Any, Optional

from ..tools import ToolContext, ToolDefinition, ToolRegistry
from .authoring import DocumentError, block_headings, report_authored_document
from .outputs import publish_copy
from .reporting import REPORT_FORMATS, build_report, report_extension, report_mime
from .tools import _owner, _service, _with_extension


def _ok(text: str, data: Optional[dict[str, Any]] = None) -> tuple[str, Any]:
    return text, data or {}


def _err(exc: Exception) -> tuple[str, Any]:
    if isinstance(exc, DocumentError):
        return f"{exc.code}: {exc.message}", {"error": exc.code, "message": exc.message}
    return f"REPORT_ERROR: {exc}", {"error": "REPORT_ERROR", "message": str(exc)}


async def _report(args: dict[str, Any], ctx: ToolContext) -> tuple[str, Any]:
    title = str(args.get("title") or "").strip()
    if not title:
        return _err(DocumentError("REPORT_TITLE_REQUIRED", "a report title is required"))
    raw_format = str(args.get("format") or "pdf").strip().casefold()
    if raw_format not in REPORT_FORMATS and raw_format not in ("md", "text"):
        return _err(DocumentError("DOCUMENT_FORMAT_UNSUPPORTED", f"unsupported report format {raw_format!r}"))
    blocks = args.get("blocks")
    sheets = args.get("sheets")
    if not blocks and not sheets:
        return _err(DocumentError("REPORT_EMPTY", "a report needs content blocks or sheets"))
    try:
        data = build_report(
            raw_format,
            title=title,
            subtitle=str(args.get("subtitle") or ""),
            blocks=blocks,
            sheets=sheets,
            footer=str(args.get("footer") or "Generated by Eclipse"),
        )
    except DocumentError as exc:
        return _err(exc)
    except Exception as exc:  # noqa: BLE001 - a renderer bug must not crash the run
        return _err(exc)

    extension = report_extension(raw_format)
    filename = str(args.get("filename") or "").strip()
    if not filename:
        from .authoring import slug_filename

        filename = slug_filename(title, extension)
    filename = _with_extension(filename, extension)
    try:
        service = _service(ctx)
        artifact = service.register_bytes(
            data,
            name=filename,
            owner_id=_owner(ctx),
            description=str(args.get("description") or f"Report: {title}"),
            mime_type=report_mime(raw_format),
            source_tool="eclipse_report",
            agent_id=str(getattr(ctx, "agent_id", None) or "eclipse-agent"),
            conversation_id=getattr(ctx, "conversation_id", None),
            run_id=getattr(ctx, "run_id", None),
            tags=list(args.get("tags") or []),
        )
    except Exception as exc:  # noqa: BLE001
        return _err(exc)

    # The writer knows the headings it wrote: record them so a contract's
    # required sections can be checked against the document (W14), with the
    # artifact id so the chat can offer the file.
    report_authored_document(
        ctx, title=title, filename=filename, headings=block_headings(blocks),
        artifact_id=str(getattr(artifact, "id", "") or ""),
        artifact_uri=f"artifact://{getattr(artifact, 'id', '')}" if getattr(artifact, "id", "") else "",
    )

    mime = report_mime(raw_format)
    # A copy the person can actually open: the Artifact Center is the catalog,
    # this is the address. The absolute path goes back in the tool result so the
    # answer can name it instead of saying "it's somewhere in Documents".
    published, note = publish_copy(data, filename, args.get("saveTo"))
    return _ok(
        f"Created {raw_format.upper()} report {artifact.name!r} "
        f"({artifact.size_bytes or len(data)} bytes) as artifact {artifact.id}.{note}",
        {
            "artifact": artifact.model_dump(by_alias=True),
            "bytes": len(data),
            "format": raw_format,
            "mimeType": mime,
            "path": published,
        },
    )


def register_report_tools(registry: ToolRegistry) -> list[str]:
    if registry.get("eclipse_report") is not None:
        return []
    registry.register(ToolDefinition(
        name="eclipse_report",
        description=(
            "Assemble and save a real report the user asked for: PDF, Word, Excel, "
            "PowerPoint, Markdown or plain text. Give a title and `blocks` "
            "(heading/paragraph/bullets/numbers/table/page_break) or `sheets` for "
            "Excel. Computed values must be labelled as computed, with their inputs "
            "and method. The file is registered in the Artifact Center AND written "
            "to a real folder (Documents/Eclipse by default, or `saveTo`); the "
            "result names its ABSOLUTE path — give that path to the user. A missing "
            "writer or storage layer is reported honestly, never replaced by a fake file."
        ),
        input_schema={
            "type": "object",
            "properties": {
                "title": {"type": "string"},
                "subtitle": {"type": "string"},
                "format": {"type": "string", "enum": ["pdf", "docx", "xlsx", "pptx", "markdown", "md", "txt", "text"]},
                "filename": {"type": "string"},
                "saveTo": {
                    "type": "string",
                    "description": "Where the readable copy goes: 'documents' (default), 'downloads', 'desktop', or an absolute folder path.",
                },
                "description": {"type": "string"},
                "footer": {"type": "string"},
                "tags": {"type": "array", "items": {"type": "string"}},
                "blocks": {
                    "type": "array",
                    "description": "Ordered content blocks for pdf/docx/markdown/txt.",
                    "items": {
                        "type": "object",
                        "properties": {
                            "type": {"type": "string", "enum": ["heading", "paragraph", "bullets", "numbers", "table", "page_break"]},
                            "text": {"type": "string"},
                            "level": {"type": "integer"},
                            "items": {"type": "array", "items": {"type": "string"}},
                            "headers": {"type": "array", "items": {"type": "string"}},
                            "rows": {"type": "array", "items": {"type": "array"}},
                        },
                        "required": ["type"],
                    },
                },
                "sheets": {
                    "type": "array",
                    "description": "Worksheets for xlsx; first row is the header.",
                    "items": {
                        "type": "object",
                        "properties": {
                            "name": {"type": "string"},
                            "rows": {"type": "array", "items": {"type": "array"}},
                        },
                    },
                },
            },
            "required": ["title"],
        },
        handler=_report,
        permission="read",
        risk="low",
        timeout_ms=60_000,
    ))
    return ["eclipse_report"]


__all__ = ["register_report_tools"]
